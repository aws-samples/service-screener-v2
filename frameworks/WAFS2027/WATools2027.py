import re

from botocore.exceptions import BotoCoreError, ClientError

from frameworks.helper.WATools import WATools
from utils.Tools import _warn, _info

BP_ID_RE = re.compile(r'^\s*((?:SEC|FND|REL|OPS|PERF|COST|SUS)\d{2}-BP\d{2})\b[\s:.-]*', re.I)

# WA Tool UpdateAnswer Notes limit.
NOTES_MAX = 2084
SS_NOTES_START = '***Generated by SS (WAFS2027)'
SS_NOTES_END = '***End of SS (WAFS2027) notes'
SS_OWNED_RE = re.compile(r'^\[ss-selected: ?(.*)\]\s*$', re.M)


def splitNotes(notes):
    """Split WA Tool notes into (customer notes, choices SS selected earlier).

    The SS block runs from SS_NOTES_START to SS_NOTES_END. Notes written by
    older WAFS2027 versions have no end marker; everything from the start
    marker on was SS-generated."""
    notes = notes or ''
    start = notes.find(SS_NOTES_START)
    if start < 0:
        return notes.strip(), []
    end = notes.find(SS_NOTES_END, start)
    if end < 0:
        block, tail = notes[start:], ''
    else:
        block, tail = notes[start:end], notes[end + len(SS_NOTES_END):]
    user = (notes[:start].rstrip() + ('\n\n' + tail.strip() if tail.strip() else '')).strip()
    owned = []
    m = SS_OWNED_RE.search(block)
    if m:
        owned = [c.strip() for c in m.group(1).split(',') if c.strip()]
    return user, owned


def composeNotes(userNotes, bodyLines, owned, limit=NOTES_MAX):
    """Customer notes first (untouched), then the SS block. Body lines are
    trimmed from the end to fit the limit. Returns None when even an empty
    SS block does not fit next to the customer's notes."""
    def build(lines, dropped):
        body = list(lines)
        if dropped:
            body.append(f"- ... and {dropped} more (see the SS WAFS2027 report)")
        block = '\n'.join([SS_NOTES_START, ''] + body + ['', f"[ss-selected: {','.join(owned)}]", SS_NOTES_END])
        return (userNotes + '\n\n' + block) if userNotes else block

    lines = list(bodyLines)
    dropped = 0
    out = build(lines, dropped)
    while len(out) > limit and lines:
        lines.pop()
        dropped += 1
        out = build(lines, dropped)
    if len(out) > limit:
        return None
    return out


def normalizeTitle(title):
    """Lower-case, strip a leading best-practice ID and non-alphanumerics, so
    'SEC01-BP01 Separate workloads using accounts' and
    'Separate workloads using accounts.' compare equal."""
    if not title:
        return ''
    t = BP_ID_RE.sub('', title)
    return re.sub(r'[^a-z0-9]+', ' ', t.lower()).strip()


class WATools2027(WATools):
    """WA Tool integration for the November 2026 Well-Architected Framework.

    Differences from the base WATools used by WAFS:
    - Best practices are matched to WA Tool choices by title (and ID when the
      choice title carries one), never by position, so renumbering or
      reordering in the lens cannot attach results to the wrong choice.
    - Choices are indexed across every pillar of the lens review, so practices
      that moved to Cloud Foundations are found wherever the lens places them.
    - Writes are skipped unless the workload's lens review is CURRENT, to avoid
      updating an older lens version whose practices differ.
    - Choices the user selected are preserved, unless the best practice
      failed SS checks in this run (then the choice is withdrawn and the
      reason is written into the notes). Choices SS itself selected in an
      earlier run are recorded in the SS notes block and withdrawn when the
      best practice no longer passes.
    - The customer's own notes are preserved; SS only rewrites its own
      delimited block inside the notes.
    - A best practice is matched by its ID first. A title is used only when
      it identifies exactly one choice in the lens; a title that maps to
      more than one choice, or an ID and title that point at different
      choices, is never matched.
    """
    DEFAULT_REPORTNAME = 'SS_Report_2027'

    def __init__(self):
        super().__init__('security')
        self.choiceIndex = {}      # BP ID / normalized title -> choice info (unambiguous keys only)
        self.ambiguousKeys = set() # BP IDs / titles that identify more than one choice
        self.titleChoices = {}     # normalized title -> [choice info, ...]
        self.choiceTitles = {}     # choiceId -> choice title
        self.questions = {}        # questionId -> {'title', 'pillarId', 'selected', 'noneChoices'}
        self.lensVersion = None
        self.lensStatus = None
        self.canWrite = False

    def preCheck(self, params):
        if 'reportName' not in params:
            params['reportName'] = self.DEFAULT_REPORTNAME
        return super().preCheck(params)

    # ------------------------------------------------------------------ #
    def _lensReview(self):
        try:
            resp = self.waClient.get_lens_review(
                WorkloadId=self.waInfo['WorkloadId'],
                LensAlias=self.waInfo['LensesAlias'],
            )
        except (ClientError, BotoCoreError) as e:
            _warn(f"[WATools2027] get_lens_review failed: {e}")
            return None
        return resp.get('LensReview', {})

    def _listAnswersForPillar(self, pillarId):
        answers, token = [], None
        while True:
            args = {
                'WorkloadId': self.waInfo['WorkloadId'],
                'LensAlias': self.waInfo['LensesAlias'],
                'PillarId': pillarId,
                'MaxResults': 50,
            }
            if token:
                args['NextToken'] = token
            resp = self.waClient.list_answers(**args)
            answers.extend(resp.get('AnswerSummaries', []))
            token = resp.get('NextToken')
            if not token:
                return answers

    def listAnswers(self):
        if self.HASPERMISSION is False or not self.waInfo.get('WorkloadId'):
            return None

        review = self._lensReview()
        if review is None:
            self.HASPERMISSION = False
            return None

        self.lensVersion = review.get('LensVersion')
        self.lensStatus = review.get('LensStatus')
        self.canWrite = self.lensStatus == 'CURRENT'
        if not self.canWrite:
            _warn(f"[WATools2027] Workload lens review is {self.lensStatus} (version {self.lensVersion}). "
                  f"Results will be shown in the report but NOT written to the WA Tool. "
                  f"Upgrade the lens review in the WA Tool console, or use a new reportName.")

        pillars = [p.get('PillarId') for p in review.get('PillarReviewSummaries', []) if p.get('PillarId')]
        if not pillars:
            pillars = ['security']

        for pillarId in pillars:
            try:
                answers = self._listAnswersForPillar(pillarId)
            except (ClientError, BotoCoreError) as e:
                _warn(f"[WATools2027] list_answers failed for pillar {pillarId}: {e}")
                continue
            for ans in answers:
                qid = ans.get('QuestionId')
                self.questions[qid] = {
                    'title': ans.get('QuestionTitle', ''),
                    'pillarId': pillarId,
                    'selected': list(ans.get('SelectedChoices', [])),
                    'noneChoices': set(),
                }
                for ch in ans.get('Choices', []):
                    if normalizeTitle(ch.get('Title')).startswith('none of these'):
                        self.questions[qid]['noneChoices'].add(ch.get('ChoiceId'))
                        continue
                    info = {
                        'questionId': qid,
                        'questionTitle': ans.get('QuestionTitle', ''),
                        'choiceId': ch.get('ChoiceId'),
                        'choiceTitle': ch.get('Title', ''),
                        'pillarId': pillarId,
                    }
                    self.choiceTitles[ch.get('ChoiceId')] = ch.get('Title', '')
                    m = BP_ID_RE.match(ch.get('Title', '') or '')
                    if m:
                        self._index(m.group(1).upper(), info)
                    key = normalizeTitle(ch.get('Title'))
                    if key:
                        self._index(key, info)
                        self.titleChoices.setdefault(key, []).append(info)

        _info(f"[WATools2027] Indexed {len(self.questions)} questions across {len(pillars)} pillars "
              f"(lens version {self.lensVersion}, status {self.lensStatus})")
        return self.choiceIndex

    def _index(self, key, info):
        """Index a key; a key seen on two different choices is ambiguous and
        is never used for matching."""
        cur = self.choiceIndex.get(key)
        if cur is None:
            if key not in self.ambiguousKeys:
                self.choiceIndex[key] = info
            return
        if (cur['questionId'], cur['choiceId']) != (info['questionId'], info['choiceId']):
            self.ambiguousKeys.add(key)
            del self.choiceIndex[key]

    def lookup(self, bpId, bpTitle, allowTitle=True, pillarFilter=None):
        """Return the WA Tool choice for a best practice, or None.

        The ID is tried first (only choice titles that carry an ID are
        indexed by ID). The title is used only when allowTitle is True and,
        among the choices allowed by pillarFilter (a callable on PillarId,
        or None for all pillars), exactly one choice has that title. When
        the ID and the title resolve to different choices the match is
        refused."""
        byId = self.choiceIndex.get((bpId or '').upper()) if bpId else None
        byTitle = None
        if allowTitle:
            cands = {(i['questionId'], i['choiceId']): i
                     for i in self.titleChoices.get(normalizeTitle(bpTitle), [])
                     if pillarFilter is None or pillarFilter(i['pillarId'])}
            if len(cands) == 1:
                byTitle = next(iter(cands.values()))
        if byId and byTitle and byId['choiceId'] != byTitle['choiceId']:
            _warn(f"[WATools2027] {bpId} matches choice {byId['choiceId']} by ID but "
                  f"{byTitle['choiceId']} by title; not written")
            return None
        return byId or byTitle

    def getAnswer(self, questionId):
        """Current answer (SelectedChoices, Notes) from the WA Tool, or None."""
        try:
            resp = self.waClient.get_answer(
                WorkloadId=self.waInfo['WorkloadId'],
                LensAlias=self.waInfo['LensesAlias'],
                QuestionId=questionId,
            )
        except (ClientError, BotoCoreError) as e:
            _warn(f"[WATools2027] get_answer failed for {questionId}: {e}")
            return None
        return resp.get('Answer', {}) or {}

    def updateAnswers(self, questionId, selectedChoices, unselectedNotes, failedChoices=None):
        """Write SS results for one question.

        selectedChoices: choices whose best practice passed in this run.
        failedChoices:   choices whose best practice failed in this run; they
                         are removed even if previously selected.
        unselectedNotes: SS note body (a string, or a list of lines).

        Choices SS selected in an earlier run (recorded in the SS notes block)
        that do not pass in this run are withdrawn. Other existing choices and
        the customer's own notes are kept. Returns the update_answer response,
        or None when nothing was written."""
        if not self.canWrite or self.HASPERMISSION is False:
            return None
        if not questionId or not self.waInfo.get('WorkloadId'):
            return None

        current = self.getAnswer(questionId)
        if current is None:
            # Without the current answer the customer's notes cannot be kept.
            _warn(f"[WATools2027] Skipping {questionId}: unable to read the current answer")
            return None

        q = self.questions.get(questionId, {})
        noneChoices = q.get('noneChoices', set())
        existing = list(current.get('SelectedChoices', q.get('selected', [])) or [])
        existingNotes = current.get('Notes', '') or ''
        userNotes, prevOwned = splitNotes(existingNotes)

        passNow = [c for c in dict.fromkeys(selectedChoices or []) if c]
        failed = set(failedChoices or [])
        passNow = [c for c in passNow if c not in failed]

        merged, withdrawn = [], []
        for c in existing:
            if c in failed or (c in prevOwned and c not in passNow):
                withdrawn.append(c)
                continue
            merged.append(c)
        if not passNow and not failed and not withdrawn and SS_NOTES_START not in existingNotes:
            # Nothing evaluated for this question and no earlier SS write to correct.
            return None

        added = [c for c in passNow if c not in merged]
        merged += added
        # "None of these" cannot be combined with other choices.
        if len(merged) > 1:
            merged = [c for c in merged if c not in noneChoices]
        owned = [c for c in merged if c in passNow and (c in prevOwned or c in added)]

        if isinstance(unselectedNotes, str):
            body = unselectedNotes.splitlines()
        else:
            body = list(unselectedNotes or [])
        if withdrawn:
            body += ['', 'Choices withdrawn by SS (best practice did not pass in this run):']
            body += [f"- {self.choiceTitles.get(c, c)}" for c in withdrawn]

        notes = composeNotes(userNotes, body, owned)
        if notes is None:
            # Without the SS block SS cannot record which choices it owns, so
            # it adds none (it could never withdraw them); withdrawals still apply.
            _warn(f"[WATools2027] {questionId}: existing notes leave no room for the SS block; "
                  f"notes left unchanged and no choices added")
            notes = existingNotes
            merged = [c for c in merged if c not in added]

        if merged == existing and notes == existingNotes:
            return None

        try:
            return self.waClient.update_answer(
                WorkloadId=self.waInfo['WorkloadId'],
                LensAlias=self.waInfo['LensesAlias'],
                QuestionId=questionId,
                SelectedChoices=merged,
                Notes=notes,
            )
        except ClientError as e:
            code = e.response.get('Error', {}).get('Code', '')
            _warn(f"[WATools2027] update_answer failed for {questionId}: {code} {e}")
            if code != 'ValidationException':
                self.HASPERMISSION = False
            return None
        except BotoCoreError as e:
            _warn(f"[WATools2027] update_answer failed for {questionId}: {e}")
            return None
